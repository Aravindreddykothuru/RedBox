function fill(text: string, vars?: Record<string, string | number>): string {
  const all = { brand: BRAND, ...vars };
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (k in all ? String(all[k as keyof typeof all]) : `{${k}}`));
}

const STORAGE_KEY = "redbox.lang";
let current: Lang = "en";
let loaded = false;
const listeners = new Set<() => void>();

function read(): Lang {
  if (!loaded) {
    loaded = true;
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === "te" || saved === "hi") current = saved;
    } catch {
      // storage blocked: English
    }
  }
  return current;
}

export function setLang(lang: Lang) {
  current = lang;
  loaded = true;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // storage blocked: the choice lasts for this page
  }
  document.documentElement.lang = lang;
  listeners.forEach((l) => l());
}

function subscribe(l: () => void) {
  listeners.add(l);
  return () => listeners.delete(l);
}

export function useI18n() {
  const lang = useSyncExternalStore(subscribe, read, () => "en" as Lang);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const t = useCallback((key: Key, vars?: Record<string, string | number>) => fill(MESSAGES[lang][key] ?? en[key], vars), [lang]);
  const genre = useCallback((g: string) => (lang === "en" ? g : (GENRES[lang][g] ?? g)), [lang]);
  /** a list of genres the way the models name them ("A and B", "A, B and more") in the chosen language */
  const genres = useCallback(
    (text: string) => {
      if (lang === "en") return text;
      const more = /^(.+), (.+) and more$/.exec(text);
      if (more) return fill(MESSAGES[lang]["list.andMore"], { first: [more[1], more[2]].map(genre).join(", ") });
      return text.split(" and ").map(genre).join(MESSAGES[lang]["list.and"]);
    },
    [lang, genre],
  );
  const reason = useCallback(
    (text: string) => {
      if (lang === "en" || !text) return text;
      for (const [pattern, key, vars] of REASONS) {
        const m = text.match(pattern);
        if (!m) continue;
        const v = vars(m);
        if (v.genre) v.genre = genre(v.genre);
        if (v.genres) v.genres = genres(v.genres);
        if (v.language) v.language = genre(v.language);
        return fill(MESSAGES[lang][key], v);
      }
      return text;
    },
    [lang, genre, genres],
  );
  const signal = useCallback((s: string) => (lang === "en" ? s : (SIGNALS[lang][s] ?? s)), [lang]);
  return { lang, setLang, t, genre, genres, reason, signal };
}
